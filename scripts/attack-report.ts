/**
 * Run the attack suite against a real Postgres (testcontainers, or PG_GUARD_TEST_ADMIN_URL/APP_URL)
 * and write docs/attack-results.md. Usage: npm run attacks
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { startTestDb } from "../test/support/db.js";
import { runAttackSuite, SAFE, SUITE_POLICY, type AttackResult } from "../test/support/run-attacks.js";

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, "\\n").replace(/\u0000/g, "\\0");
const code = (s: string) => "`" + esc(s.length > 110 ? `${s.slice(0, 107)}...` : s) + "`";

export function renderReport(results: AttackResult[], pgVersion: string): string {
  const n = results.length;
  const guardedSafe = results.filter((r) => SAFE.includes(r.guarded.verdict)).length;
  const blocked = results.filter((r) => r.guarded.verdict === "blocked").length;
  const contained = results.filter((r) => r.guarded.verdict === "contained").length;
  const stopped = results.filter((r) => r.guarded.verdict === "stopped").length;
  const dbSafe = results.filter((r) => SAFE.includes(r.dbOnly.verdict)).length;
  const dbFails = results.filter((r) => !SAFE.includes(r.dbOnly.verdict));
  const cats = [...new Set(results.map((r) => r.attack.category))];

  const lines: string[] = [];
  lines.push(`# Attack suite results`, ``);
  lines.push(`Generated by \`npm run attacks\` on ${new Date().toISOString().slice(0, 10)} against ${pgVersion} in Docker.`);
  lines.push(`Attacker: user \`alice\` (\`app.user_id = 'alice'\`), role \`${SUITE_POLICY.role}\`, timeout ${SUITE_POLICY.timeoutMs} ms, row cap ${SUITE_POLICY.maxRows}.`);
  lines.push(`A result is a **leak** if it contains any secret marker (Bob's rows, password hashes, API keys), a **write** if any table, row, or function changed, **slow** if it ran longer than the timeout + 2.5 s.`, ``);
  lines.push(`| | Attacks | Safe | Leaks / writes / slow |`, `|---|---:|---:|---:|`);
  lines.push(`| **pg-guard-sql (all layers)** | ${n} | **${guardedSafe}/${n}** (${blocked} blocked by the validator, ${contained} ran but contained, ${stopped} stopped by Postgres) | ${n - guardedSafe} |`);
  lines.push(`| Database layers only (validator removed) | ${n} | ${dbSafe}/${n} | ${n - dbSafe} |`, ``);
  if (dbFails.length) {
    lines.push(`Without the validator, these got through the database layers, which is why the parser allowlist exists:`, ``);
    for (const r of dbFails) lines.push(`- #${r.attack.id} ${r.attack.name}: **${r.dbOnly.verdict}** (${esc(r.dbOnly.detail)})`);
    lines.push(``);
  }
  lines.push(`## By category`, ``, `| Category | Attacks | Safe (all layers) | Safe (DB layers only) |`, `|---|---:|---:|---:|`);
  for (const c of cats) {
    const rs = results.filter((r) => r.attack.category === c);
    lines.push(`| ${c} | ${rs.length} | ${rs.filter((r) => SAFE.includes(r.guarded.verdict)).length} | ${rs.filter((r) => SAFE.includes(r.dbOnly.verdict)).length} |`);
  }
  lines.push(``, `## Every attack`, ``, `| # | Category | Attack | SQL | pg-guard-sql | DB layers only |`, `|---:|---|---|---|---|---|`);
  for (const r of results) {
    const g = r.guarded.verdict === "blocked" ? `blocked: ${r.guarded.code}` : `${r.guarded.verdict}: ${r.guarded.detail}`;
    const d = `${r.dbOnly.verdict}: ${r.dbOnly.detail}`;
    lines.push(`| ${r.attack.id} | ${r.attack.category} | ${esc(r.attack.name)} | ${code(r.attack.sql)} | ${SAFE.includes(r.guarded.verdict) ? "✅" : "❌"} ${esc(g)} | ${SAFE.includes(r.dbOnly.verdict) ? "✅" : "❌"} ${esc(d)} |`);
  }
  lines.push(``);
  return lines.join("\n");
}

async function main() {
  const db = await startTestDb();
  try {
    const pg = await import("pg");
    const c = new pg.default.Client({ connectionString: db.adminUrl });
    await c.connect();
    const v = (await c.query("SHOW server_version")).rows[0].server_version as string;
    await c.end();
    const results = await runAttackSuite(db.adminUrl, db.appUrl);
    const md = renderReport(results, `PostgreSQL ${v.split(" ")[0]}`);
    const out = fileURLToPath(new URL("../docs/attack-results.md", import.meta.url));
    writeFileSync(out, md);
    process.stdout.write(md.split("## By category")[0]);
    process.stdout.write(`\nWrote ${out}\n`);
    if (results.some((r) => !SAFE.includes(r.guarded.verdict))) process.exitCode = 1;
  } finally {
    await db.stop();
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
